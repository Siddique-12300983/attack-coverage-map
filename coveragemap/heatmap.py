def _depth_class(depth: int) -> str:
    if depth >= 3:
        return "d3"
    if depth == 2:
        return "d2"
    return "d1"


def build_html(
    coverage: Coverage,
    title: str = "Detection coverage",
    subtitle: Optional[str] = None,
) -> str:
    esc = html.escape
    summary = coverage.summary()
    grouped = coverage.by_tactic()
    gaps_by_tactic: Dict[str, List[str]] = {}
    for technique in coverage.gaps():
        for tactic in coverage.attack.tactics_for(technique) or ["unmapped"]:
            gaps_by_tactic.setdefault(tactic, []).append(technique)

    columns = sorted(
        set(grouped).union(gaps_by_tactic),
        key=coverage.attack.sort_key,
    )

    parts: List[str] = []
    parts.append("<!doctype html>")
    parts.append('<html lang="en"><head><meta charset="utf-8">')
    parts.append('<meta name="viewport" content="width=device-width, initial-scale=1">')
    parts.append("<title>%s</title>" % esc(title))
    parts.append("<style>%s</style></head><body><div class='wrap'>" % STYLE)
    parts.append(
        '<h1><span class="tilde">~/</span>%s</h1>' % esc(title)
    )
    parts.append(
        '<p class="sub">%s</p>'
        % esc(
            subtitle
            or "Generated by attack-coverage-map on %s"
            % time.strftime("%Y-%m-%d %H:%M")
        )
    )

    tiles = [
        ("detections", summary["detections"]),
        ("techniques", summary["techniques_covered"]),
        ("tactics", summary["tactics_covered"]),
        ("single detection", summary["techniques_with_one_detection"]),
    ]
    if coverage.targets:
        tiles.append(("target gaps", summary["targets_missing"]))
        tiles.append(("target covered", "%s%%" % summary["target_percent"]))
    parts.append('<div class="stats">')
    for label, value in tiles:
        parts.append(
            '<div class="stat"><b>%s</b><span>%s</span></div>' % (esc(str(value)), esc(label))
        )
    parts.append("</div>")

    parts.append('<div class="legend">')
    parts.append('<span><i style="background:#1f2740;border:1px solid #2c3a63"></i>1 detection</span>')
    parts.append('<span><i style="background:#1f3042;border:1px solid #2d4a63"></i>2 detections</span>')
    parts.append('<span><i style="background:#223524;border:1px solid #37562f"></i>3 or more</span>')
    parts.append('<span><i style="background:#2e1d26;border:1px dashed #5b2c3a"></i>target, no detection</span>')
    parts.append("</div>")

    parts.append('<div class="matrix">')
    for tactic in columns:
        label = coverage.attack.tactic_names.get(tactic, tactic.replace("-", " "))
        entries = grouped.get(tactic, [])
        gaps = gaps_by_tactic.get(tactic, [])
        parts.append('<div class="col">')
        parts.append(
            "<h2>%s <em>%d</em></h2>" % (esc(label), len(entries) + len(gaps))
        )
        if not entries and not gaps:
            parts.append('<p class="empty">nothing yet</p>')
        for entry in entries:
            detections = ", ".join(
                "%s (%s)" % (d.name, d.repo or d.kind) for d in entry.detections
            )
            parts.append(
                '<a class="cell %s" href="%s" title="%s" target="_blank" rel="noopener">'
                '<span class="id">%s</span><span class="nm">%s</span>'
                '<span class="mt">%d detection%s &middot; %s</span></a>'
                % (
                    _depth_class(entry.depth),
                    esc(coverage.attack.url(entry.technique)),
                    esc(detections),
                    esc(entry.technique),
                    esc(entry.name),
                    entry.depth,
                    "" if entry.depth == 1 else "s",
                    esc(", ".join(entry.sources)),
                )
            )
        for technique in sorted(gaps):
            parts.append(
                '<a class="cell gap" href="%s" title="on the target list, no detection yet" '
                'target="_blank" rel="noopener"><span class="id">%s</span>'
                '<span class="nm">%s</span><span class="mt">no detection yet</span></a>'
                % (
                    esc(coverage.attack.url(technique)),
                    esc(technique),
                    esc(coverage.attack.name(technique)),
                )
            )
        parts.append("</div>")
    parts.append("</div>")

    if coverage.detections:
        parts.append("<h2 style='font-size:13px;margin:36px 0 0;color:#fff'>Detections behind this map</h2>")
        parts.append('<table class="list"><tr><th>Detection</th><th>Source</th>'
                     "<th>Level</th><th>Techniques</th></tr>")
        for detection in sorted(coverage.detections, key=lambda d: (d.repo or d.kind, d.name)):
            parts.append(
                "<tr><td>%s</td><td>%s</td><td>%s</td><td class='t'>%s</td></tr>"
                % (
                    esc(detection.name),
                    esc(detection.repo or detection.kind),
                    esc(detection.level),
                    esc(", ".join(detection.techniques) or "none"),
                )
            )
        parts.append("</table>")

    parts.append(
        '<p class="note">Coverage here means a detection exists and claims the '
        "technique. It does not mean the detection was tested against a live "
        "attack, and it does not mean the technique is fully covered. Depth is "
        "the number of independent detections behind a technique, which is the "
        "number worth growing. Built by "
        '<a href="https://ruxchipher.com">ruxchipher</a> &middot; '
        '<a href="https://github.com/Siddique-12300983/attack-coverage-map">'
        "attack-coverage-map</a>.</p>"
    )
    parts.append("</div></body></html>")
    return "\n".join(parts)


def write_html(coverage: Coverage, path: str, **kwargs) -> str:
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(build_html(coverage, **kwargs))
        handle.write("\n")
    return path
