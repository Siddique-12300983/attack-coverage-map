"""Write an ATT&CK Navigator layer file.

The layer format is documented by MITRE; this writes version 4.5, which the
hosted Navigator at mitre-attack.github.io/attack-navigator reads. Open the
Navigator, choose "Open Existing Layer", then "Upload from Local".
"""

import json
from typing import Dict, List, Optional

from .coverage import Coverage

LAYER_VERSION = "4.5"
NAVIGATOR_VERSION = "4.9.0"
ATTACK_VERSION = "14"

# Tokyo Night, so the layer matches the rest of my tooling.
GRADIENT = ["#1a1b26", "#3d59a1", "#7aa2f7", "#9ece6a"]
GAP_COLOR = "#f7768e"


def build_layer(
    coverage: Coverage,
    name: str = "ruxchipher detection coverage",
    description: Optional[str] = None,
    include_gaps: bool = True,
) -> Dict:
    """Turn a Coverage into a Navigator layer dictionary."""
    max_depth = max((e.depth for e in coverage.techniques.values()), default=1)
    entries: List[Dict] = []

    for technique in sorted(coverage.techniques):
        entry = coverage.techniques[technique]
        detections = "; ".join(
            "%s (%s)" % (d.name, d.repo or d.kind) for d in entry.detections
        )
        metadata = [
            {"name": "detections", "value": str(entry.depth)},
            {"name": "sources", "value": ", ".join(entry.sources)},
        ]
        if not entry.known:
            metadata.append(
                {"name": "note", "value": "not in the bundled ATT&CK table"}
            )
        tactics = entry.tactics or [None]
        for tactic in tactics:
            item = {
                "techniqueID": technique,
                "score": entry.depth,
                "color": "",
                "comment": detections,
                "enabled": True,
                "metadata": metadata,
                "links": [],
                "showSubtechniques": "." in technique,
            }
            if tactic and tactic != "unmapped":
                item["tactic"] = tactic
            entries.append(item)

    if include_gaps:
        for technique in coverage.gaps():
            tactics = coverage.attack.tactics_for(technique) or [None]
            for tactic in tactics:
                item = {
                    "techniqueID": technique,
                    "color": GAP_COLOR,
                    "comment": "on my target list with no detection behind it yet",
                    "enabled": True,
                    "metadata": [{"name": "status", "value": "gap"}],
                    "links": [],
                    "showSubtechniques": "." in technique,
                }
                if tactic:
                    item["tactic"] = tactic
                entries.append(item)

    if description is None:
        summary = coverage.summary()
        description = (
            "%d detections covering %d ATT&CK techniques across %d tactics. "
            "Score is how many independent detections back a technique. "
            "Red cells are target techniques with no detection yet. "
            "Generated by attack-coverage-map."
            % (
                summary["detections"],
                summary["techniques_covered"],
                summary["tactics_covered"],
            )
        )

    return {
        "name": name,
        "versions": {
            "attack": ATTACK_VERSION,
            "navigator": NAVIGATOR_VERSION,
            "layer": LAYER_VERSION,
        },
        "domain": "enterprise-attack",
        "description": description,
        "filters": {"platforms": ["Windows", "Linux", "macOS"]},
        "sorting": 3,
        "layout": {
            "layout": "side",
            "aggregateFunction": "max",
            "showID": True,
            "showName": True,
            "showAggregateScores": False,
            "countUnscored": False,
        },
        "hideDisabled": False,
        "techniques": entries,
        "gradient": {
            "colors": GRADIENT[: max(2, min(len(GRADIENT), max_depth + 1))],
            "minValue": 1,
            "maxValue": max(1, max_depth),
        },
        "legendItems": [
            {"label": "1 detection", "color": GRADIENT[1]},
            {"label": "2 or more detections", "color": GRADIENT[-1]},
            {"label": "target with no detection", "color": GAP_COLOR},
        ],
        "metadata": [
            {"name": "generator", "value": "attack-coverage-map"},
            {"name": "detections", "value": str(len(coverage.detections))},
        ],
        "showTacticRowBackground": True,
        "tacticRowBackground": "#21283b",
        "selectTechniquesAcrossTactics": True,
        "selectSubtechniquesWithParent": False,
    }


def write_layer(coverage: Coverage, path: str, **kwargs) -> str:
    layer = build_layer(coverage, **kwargs)
    with open(path, "w", encoding="utf-8") as handle:
        json.dump(layer, handle, indent=2)
        handle.write("\n")
    return path
